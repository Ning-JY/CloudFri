// 均按各计费依据文件原文移植；本文件为系统内唯一实现，页面只负责表单与展示。
function fmtYuan(v){ return v.toLocaleString("zh-CN",{minimumFractionDigits:2, maximumFractionDigits:2}); }
function fmtWan(v){ return v.toLocaleString("zh-CN",{minimumFractionDigits:4, maximumFractionDigits:4}); }
function rmbUpper(n){
  if(!(n>0)) return "零元整";
  var digits=["零","壹","贰","叁","肆","伍","陆","柒","捌","玖"], units=["","拾","佰","仟"], big=["","万","亿","兆"];
  var s = Math.round(n*100).toString(); // 分
  var fen = s.slice(-2).padStart(2,"0"), intPart = s.slice(0,-2) || "0";
  var out="", zero=false, groups=[];
  while(intPart.length>0){ groups.unshift(intPart.slice(-4)); intPart=intPart.slice(0,-4); }
  for(var g=0; g<groups.length; g++){
    var grp=groups[g].padStart(4,"0"), gtxt="";
    for(var i=0;i<4;i++){
      var d=+grp[i];
      if(d===0){ zero=true; }
      else { if(zero && gtxt) gtxt+="零"; zero=false; gtxt+=digits[d]+units[3-i]; }
    }
    if(gtxt) out+=gtxt+big[groups.length-1-g];
    else if(out && !out.endsWith("零")) out+="零";
  }
  out = out.replace(/零+$/,"") + "元";
  var jiao=+fen[0], f=+fen[1];
  if(jiao===0 && f===0) out+="整";
  else { if(jiao) out+=digits[jiao]+"角"; else if(f) out+="零"; if(f) out+=digits[f]+"分"; }
  return out;
}
/* 差额定率累进：amount 万元，tiers=[[上限万元, 费率(小数)],...] 末档上限用 Infinity。返回 {fee:万元, proc} */
function tiered(amount, tiers, rateLabel){
  var fee=0, prev=0, parts=[];
  for(var i=0;i<tiers.length;i++){
    if(amount<=prev) break;
    var seg=Math.min(amount, tiers[i][0])-prev;
    if(seg>0){ fee += seg*tiers[i][1]; parts.push(fmtWan(seg)+"×"+rateLabel(tiers[i][1])); }
    prev=tiers[i][0];
  }
  return { fee: fee, proc: parts.join(" + ") };
}
/* 点值内插：points=[[x,y],...] 升序；x 小于首点按原点比例，大于末点按末段斜率延伸 */
function interp(points, x){
  if(x<=0) return { y:0, proc:"0" };
  var p0=points[0];
  if(x<=p0[0]){ var y0=p0[1]*x/p0[0]; return { y:y0, proc:"按首点比例 "+fmtWan(x)+"/"+p0[0]+"×"+p0[1]+"="+fmtWan(y0) }; }
  for(var i=1;i<points.length;i++){
    if(x<=points[i][0]){
      var a=points[i-1], b=points[i], y=a[1]+(b[1]-a[1])*(x-a[0])/(b[0]-a[0]);
      return { y:y, proc:"内插："+a[1]+"+("+b[1]+"-"+a[1]+")×("+fmtWan(x)+"-"+a[0]+")/("+(b[0]-a[0])+")="+fmtWan(y) };
    }
  }
  var a2=points[points.length-2], b2=points[points.length-1];
  var y2=b2[1]+(b2[1]-a2[1])*(x-b2[0])/(b2[0]-a2[0]);
  return { y:y2, proc:"超末点按末段斜率延伸："+b2[1]+"+("+(b2[1]-a2[1])+")×("+fmtWan(x)+"-"+b2[0]+")/("+(b2[0]-a2[0])+")="+fmtWan(y2) };
}
/* 区间表插入法：brackets=[[下限,上限或null,费下限,费上限或null],...]（同单位）
   档内按插入法得单值；最高档（无上限）或未达首档下限时返回该档费用区间 */
function rangeFee(brackets, x){
  for(var i=0;i<brackets.length;i++){
    var b=brackets[i], lo=b[0], hi=b[1], fl=b[2], fh=(b[3]==null? b[2] : b[3]);
    if(hi!=null && x>hi) continue;
    if(hi==null){ return { r:[fl, fh], proc:"最高档（"+lo+" 以上），按文件区间 "+fl+"–"+fh+" 计" }; }
    if(x<=lo){ return { r:[fl, fh], proc:"未达首档下限，按首档区间 "+fl+"–"+fh+" 计（参考）" }; }
    var t=(x-lo)/(hi-lo);
    var v=fl+(fh-fl)*t;
    return { r:[v, v], proc:"插入法："+fl+"+("+fh+"-"+fl+")×("+fmtWan(x)+"-"+lo+")/("+(hi-lo)+")="+fmtWan(v) };
  }
  var last=brackets[brackets.length-1];
  return { r:[last[2], last[3]==null? last[2]: last[3]], proc:"超出最高档，按最高档区间计" };
}
